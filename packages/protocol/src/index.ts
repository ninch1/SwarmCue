import { z } from "zod";

/** Shared client-server message contract. */
export const ProtocolVersion = 4 as const;

export type ProtocolVersion = typeof ProtocolVersion;

/** Digits and uppercase letters without look-alikes (0/O, 1/I). 32 characters. */
export const ROOM_ID_ALPHABET = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ";
export const ROOM_ID_LENGTH = 8;
export const DISPLAY_NAME_MAX_LENGTH = 32;
export const MAGNET_URI_MAX_LENGTH = 2048;
export const MEDIA_NAME_MAX_LENGTH = 255;
export const CLOCK_PING_ID_MAX = 2_147_483_647;
/** Generous upper bound for a media position: one week. */
export const POSITION_SECONDS_MAX = 7 * 24 * 60 * 60;
export const SUBTITLE_NAME_MAX_LENGTH = 255;
/**
 * Largest shared subtitle, in UTF-8 bytes of normalized WebVTT. Feature-length
 * subtitles are typically 50–300 KB.
 */
export const SHARED_SUBTITLE_MAX_BYTES = 512 * 1024;

const NO_CONTROL_CHARACTERS = /^\P{Cc}+$/u;

/**
 * Length of `text` encoded as UTF-8, without TextEncoder or Buffer so this
 * package stays free of DOM/Node globals. A lone surrogate counts as the
 * 3-byte replacement character it is encoded as.
 */
export function utf8ByteLength(text: string): number {
  let bytes = 0;
  for (let index = 0; index < text.length; index += 1) {
    const code = text.charCodeAt(index);
    if (code < 0x80) {
      bytes += 1;
    } else if (code < 0x800) {
      bytes += 2;
    } else if (code >= 0xd800 && code <= 0xdbff && isLowSurrogate(text.charCodeAt(index + 1))) {
      bytes += 4;
      index += 1;
    } else {
      bytes += 3;
    }
  }
  return bytes;
}

function isLowSurrogate(code: number): boolean {
  return code >= 0xdc00 && code <= 0xdfff;
}

export const RoomIdSchema = z
  .string()
  .regex(
    new RegExp(`^[${ROOM_ID_ALPHABET}]{${ROOM_ID_LENGTH}}$`),
    `Room codes are ${ROOM_ID_LENGTH} letters and digits.`,
  );

export const DisplayNameSchema = z
  .string()
  .trim()
  .min(1, "Enter a display name.")
  .max(
    DISPLAY_NAME_MAX_LENGTH,
    `Display names can be at most ${DISPLAY_NAME_MAX_LENGTH} characters.`,
  )
  .regex(NO_CONTROL_CHARACTERS, "Display names cannot contain control characters.");

export const ParticipantIdSchema = z.string().min(1).max(64);

/**
 * `connected` is false while the participant's connection is down and the
 * server is holding their place for the reconnect grace period.
 */
export const ParticipantSchema = z.strictObject({
  id: ParticipantIdSchema,
  displayName: DisplayNameSchema,
  connected: z.boolean(),
});

/**
 * Secret proof of a participant session: 32 random bytes as base64url.
 * Sent only to the participant who owns it; never part of room state.
 */
export const ResumeTokenSchema = z
  .string()
  .regex(/^[A-Za-z0-9_-]{43}$/, "Invalid resume token.");

/**
 * Internal magnet generated by the host's browser for the selected file.
 * BitTorrent v1: the info hash is 40 hex or 32 base32 characters.
 * A regex rather than URLSearchParams keeps this package free of DOM/Node globals.
 */
export const MagnetUriSchema = z
  .string()
  .max(MAGNET_URI_MAX_LENGTH, "Magnet URI is too long.")
  .regex(
    /^magnet:\?(?:.*&)?xt=urn:btih:(?:[0-9a-f]{40}|[a-z2-7]{32})(?:&|$)/i,
    "Invalid magnet URI.",
  );

/** What the host shares with the room: the internal magnet plus file metadata. */
export const SharedMediaSchema = z.strictObject({
  magnetUri: MagnetUriSchema,
  name: z
    .string()
    .trim()
    .min(1)
    .max(MEDIA_NAME_MAX_LENGTH)
    .regex(NO_CONTROL_CHARACTERS, "Media names cannot contain control characters.")
    .nullable(),
  sizeBytes: z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER).nullable(),
});

export const PlaybackStatusSchema = z.enum(["playing", "paused"]);

export const PositionSecondsSchema = z
  .number()
  .finite()
  .nonnegative()
  .max(POSITION_SECONDS_MAX);

/**
 * Shared playback timeline: the media position at the server time of the
 * latest accepted change. While playing, clients compute the current
 * position as `positionSeconds + (serverNow - updatedAtServerMs) / 1000`.
 * `revision` increases on every accepted change, so clients can tell a new
 * command apart from an unchanged snapshot.
 */
export const PlaybackStateSchema = z.strictObject({
  status: PlaybackStatusSchema,
  positionSeconds: PositionSecondsSchema,
  updatedAtServerMs: z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER),
  revision: z.number().int().nonnegative(),
});

/** Server-generated: 16 random bytes as base64url. New for every shared subtitle. */
export const SubtitleIdSchema = z
  .string()
  .regex(/^[A-Za-z0-9_-]{22}$/, "Invalid subtitle id.");

export const SubtitleNameSchema = z
  .string()
  .trim()
  .min(1, "Subtitle names cannot be empty.")
  .max(SUBTITLE_NAME_MAX_LENGTH, "Subtitle name is too long.")
  .regex(NO_CONTROL_CHARACTERS, "Subtitle names cannot contain control characters.");

/**
 * Normalized WebVTT as produced by the web client. The server only checks its
 * size and overall shape; browsers parse the cues themselves.
 */
export const SharedSubtitleContentSchema = z
  .string()
  // UTF-16 length never exceeds the UTF-8 length, so this cheaply bounds the exact check.
  .max(SHARED_SUBTITLE_MAX_BYTES, "Shared subtitles can be at most 512 KB.")
  .refine((text) => utf8ByteLength(text) <= SHARED_SUBTITLE_MAX_BYTES, {
    message: "Shared subtitles can be at most 512 KB.",
  })
  .refine((text) => /^WEBVTT(?:[ \t][^\n]*)?\n/.test(text), {
    message: "Shared subtitles must be WebVTT.",
  })
  // Normalized text uses LF line endings; only tabs and newlines are allowed as controls.
  .refine((text) => !/[\u0000-\u0008\u000B-\u001F\u007F]/.test(text), {
    message: "Shared subtitles cannot contain control characters.",
  })
  .refine((text) => text.endsWith("\n"), {
    message: "Shared subtitles must end with a newline.",
  })
  .refine((text) => /^(?:\d{2,}:)?\d{2}:\d{2}\.\d{3}[ \t]+-->/m.test(text), {
    message: "Shared subtitles must contain at least one cue.",
  });

/** What the room knows about its shared subtitle. The text itself is sent separately. */
export const SharedSubtitleMetadataSchema = z.strictObject({
  id: SubtitleIdSchema,
  name: SubtitleNameSchema,
  /** UTF-8 bytes of the WebVTT text, measured by the server. */
  sizeBytes: z.number().int().min(1).max(SHARED_SUBTITLE_MAX_BYTES),
  /** Who shared it; they may have left the room since. */
  sharedBy: ParticipantIdSchema,
});

/**
 * Complete description of a room at one moment. Participants are in join
 * order. A shared subtitle appears only as metadata; its text is delivered
 * in `subtitle.content`, so snapshots stay small.
 */
export const RoomSnapshotSchema = z
  .strictObject({
    roomId: RoomIdSchema,
    hostId: ParticipantIdSchema,
    participants: z.array(ParticipantSchema),
    media: SharedMediaSchema.nullable(),
    playback: PlaybackStateSchema,
    subtitle: SharedSubtitleMetadataSchema.nullable(),
  })
  .refine(
    (snapshot) =>
      snapshot.participants.some((participant) => participant.id === snapshot.hostId),
    { message: "The host must be one of the participants.", path: ["hostId"] },
  );

/** Matches a clock.pong to the client's pending sample. */
export const ClockPingIdSchema = z.number().int().min(0).max(CLOCK_PING_ID_MAX);

// Client → server

/**
 * Any connection, in a room or not: ask for the server clock. Browser
 * JavaScript cannot use native WebSocket ping/pong frames, so this is an
 * ordinary protocol message.
 */
export const ClockPingMessageSchema = z.strictObject({
  type: z.literal("clock.ping"),
  protocolVersion: z.literal(ProtocolVersion),
  id: ClockPingIdSchema,
});

export const RoomCreateMessageSchema = z.strictObject({
  type: z.literal("room.create"),
  protocolVersion: z.literal(ProtocolVersion),
  displayName: DisplayNameSchema,
});

export const RoomJoinMessageSchema = z.strictObject({
  type: z.literal("room.join"),
  protocolVersion: z.literal(ProtocolVersion),
  roomId: RoomIdSchema,
  displayName: DisplayNameSchema,
});

/** Reclaim an existing participant session on a new connection. */
export const RoomResumeMessageSchema = z.strictObject({
  type: z.literal("room.resume"),
  protocolVersion: z.literal(ProtocolVersion),
  roomId: RoomIdSchema,
  resumeToken: ResumeTokenSchema,
});

/** Leave the room deliberately, skipping the reconnect grace period. */
export const RoomLeaveMessageSchema = z.strictObject({
  type: z.literal("room.leave"),
  protocolVersion: z.literal(ProtocolVersion),
});

/** Host only: replace the room's shared media. */
export const MediaSetMessageSchema = z.strictObject({
  type: z.literal("media.set"),
  protocolVersion: z.literal(ProtocolVersion),
  media: SharedMediaSchema,
});

/**
 * Any participant: play, pause, or seek. The sender reports its own current
 * position; a seek is the current status with a new position.
 */
export const PlaybackSetMessageSchema = z.strictObject({
  type: z.literal("playback.set"),
  protocolVersion: z.literal(ProtocolVersion),
  status: PlaybackStatusSchema,
  positionSeconds: PositionSecondsSchema,
});

/**
 * Any participant: share a subtitle with the room, replacing the current one
 * (last write wins). `mediaMagnetUri` names the media it was chosen for; the
 * server rejects it if the room's media has changed since.
 */
export const SubtitleSetMessageSchema = z.strictObject({
  type: z.literal("subtitle.set"),
  protocolVersion: z.literal(ProtocolVersion),
  name: SubtitleNameSchema,
  content: SharedSubtitleContentSchema,
  mediaMagnetUri: MagnetUriSchema,
});

/**
 * Any participant: remove the shared subtitle for everyone. Only removes the
 * subtitle with this id, so nobody removes one they have not seen.
 */
export const SubtitleRemoveMessageSchema = z.strictObject({
  type: z.literal("subtitle.remove"),
  protocolVersion: z.literal(ProtocolVersion),
  id: SubtitleIdSchema,
});

export const ClientMessageSchema = z.discriminatedUnion("type", [
  ClockPingMessageSchema,
  RoomCreateMessageSchema,
  RoomJoinMessageSchema,
  RoomResumeMessageSchema,
  RoomLeaveMessageSchema,
  MediaSetMessageSchema,
  PlaybackSetMessageSchema,
  SubtitleSetMessageSchema,
  SubtitleRemoveMessageSchema,
]);

// Server → client

export const ErrorCodeSchema = z.enum([
  "invalid_message",
  "unsupported_version",
  "room_not_found",
  "room_full",
  "already_in_room",
  "not_in_room",
  "not_host",
  "no_media",
  /** The room's media changed after the client chose a subtitle for it. */
  "media_changed",
  /** Unknown room, wrong token, or expired session; deliberately not more specific. */
  "resume_rejected",
  /** Another connection resumed this session; this one is closed and must not reconnect. */
  "session_replaced",
  "internal_error",
]);

/**
 * Sent only to the participant who created or joined the room. The resume
 * token lets that participant reclaim the session after a dropped connection.
 */
export const RoomJoinedMessageSchema = z.strictObject({
  type: z.literal("room.joined"),
  selfId: ParticipantIdSchema,
  resumeToken: ResumeTokenSchema,
  snapshot: RoomSnapshotSchema,
});

/** Sent only to the connection that resumed a session. */
export const RoomResumedMessageSchema = z.strictObject({
  type: z.literal("room.resumed"),
  selfId: ParticipantIdSchema,
  snapshot: RoomSnapshotSchema,
});

/**
 * Sent whenever room membership, a participant's connection status, host,
 * shared media, playback, or the shared subtitle changes.
 */
export const RoomSnapshotMessageSchema = z.strictObject({
  type: z.literal("room.snapshot"),
  snapshot: RoomSnapshotSchema,
});

export const ErrorMessageSchema = z.strictObject({
  type: z.literal("error"),
  code: ErrorCodeSchema,
  message: z.string(),
});

/** Reply to clock.ping. `serverTimeMs` is the server's Date.now() when replying. */
export const ClockPongMessageSchema = z.strictObject({
  type: z.literal("clock.pong"),
  id: ClockPingIdSchema,
  serverTimeMs: z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER),
});

/**
 * The text of the room's shared subtitle. Sent after the snapshot that names
 * this id: to everyone when it is set, and to a participant after joining or
 * resuming. Clients use it only while their latest snapshot has the same id.
 */
export const SubtitleContentMessageSchema = z.strictObject({
  type: z.literal("subtitle.content"),
  id: SubtitleIdSchema,
  content: SharedSubtitleContentSchema,
});

export const ServerMessageSchema = z.discriminatedUnion("type", [
  RoomJoinedMessageSchema,
  RoomResumedMessageSchema,
  RoomSnapshotMessageSchema,
  ErrorMessageSchema,
  ClockPongMessageSchema,
  SubtitleContentMessageSchema,
]);

